"""Regenerate the figures, the fault matrix and the sample reports used in the README.

Run from the project root:  python scripts/generate_docs.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from railway_commissioning.commissioning import run_commissioning_suite  # noqa: E402
from railway_commissioning.plotting import scenario_svg  # noqa: E402
from railway_commissioning.reporting import results_to_csv, results_to_html  # noqa: E402
from railway_commissioning.scenarios import fault_matrix_markdown, run_fault_matrix  # noqa: E402


def main() -> int:
    images = ROOT / "docs" / "images"
    images.mkdir(parents=True, exist_ok=True)
    matrix = run_fault_matrix()
    for result in matrix:
        (images / f"scenario_{result.name}.svg").write_text(scenario_svg(result), encoding="utf-8")

    header = (
        "# Fault matrix\n\n"
        "Generated by `python scripts/generate_docs.py`. Every scenario runs the same profile "
        "(OPEN at 0 s, CLOSE at 4 s, end at 8 s). The detection only uses measured values "
        "(telemetry and protection trips), not the name of the injected fault.\n\n"
    )
    plots = "\n## Plots\n\n" + "\n".join(f"- [{r.name}](images/scenario_{r.name}.svg)" for r in matrix) + "\n"
    (ROOT / "docs" / "fault_matrix.md").write_text(header + fault_matrix_markdown(matrix) + plots, encoding="utf-8")

    results = run_commissioning_suite()
    reports = ROOT / "reports"
    reports.mkdir(exist_ok=True)
    (reports / "sample_commissioning_report.csv").write_text(results_to_csv(results), encoding="utf-8")
    (reports / "sample_commissioning_report.html").write_text(results_to_html(results), encoding="utf-8")

    failed = [r.name for r in matrix if not r.passed] + [r.test_id for r in results if not r.passed]
    print(f"{len(matrix)} scenarios, {len(results)} commissioning tests, failed: {failed or 'none'}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
